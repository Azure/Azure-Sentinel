"""Build an inline, synthetic-only KQL regression query from the current YAML."""

import hashlib
import json
from pathlib import Path
import yaml


ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
PARSERS = HERE.parent / "Parsers"
REGULAR = "ASimEmailEventMicrosoftDefenderOffice365"
FILTERING = "vimEmailEventMicrosoftDefenderOffice365"


def literal(value, kind):
    if kind == "string":
        return json.dumps("" if value is None else str(value))
    if kind == "dynamic":
        return "dynamic(" + json.dumps(value, separators=(",", ":")) + ")"
    if value is None:
        return kind + "(null)"
    if kind == "datetime":
        return "datetime(" + value + ")"
    if kind == "bool":
        return str(value).lower()
    if kind == "guid":
        return "guid(" + str(value) + ")"
    return str(value)


def declaration(name):
    path = PARSERS / (name + ".yaml")
    definition = yaml.safe_load(path.read_text(encoding="utf-8"))
    params = []
    for param in definition.get("ParserParams", []):
        value = param["Default"]
        default = json.dumps(value) if param["Type"] == "string" else str(value).lower() if isinstance(value, bool) else str(value)
        params.append(param["Name"] + ":" + param["Type"] + "=" + default)
    digest = hashlib.sha256(path.read_text(encoding="utf-8-sig").encode("utf-8")).hexdigest()
    query = "\n".join(line.rstrip() for line in definition["ParserQuery"].splitlines())
    return f"// source-sha256 {name}: {digest}\nlet {name} = ({', '.join(params)}) {{\n{query}\n}};\n"


def count_test(name, query, expected):
    return f'(print Test="{name}", Field="RowCount", Expected="{expected}", Actual=tostring(toscalar({query} | count)))'


def build():
    fixtures = json.loads((HERE / "EmailEventsSynthetic.json").read_text(encoding="utf-8"))
    schema = json.loads((ROOT / ".script" / "tests" / "KqlvalidationsTests" / "CustomTables" / "EmailEvents.json").read_text(encoding="utf-8"))["Properties"]
    source_rows = [", ".join(literal(case["source"].get(field["name"]), field["type"]) for field in schema)
                   for case in fixtures["cases"]]
    result = "// Synthetic fixtures only. Zero result rows means all assertions passed when executed.\n"
    result += "// This file is generated by build_regression.py; do not hand-edit.\n"
    result += "let EmailEvents = datatable(" + ", ".join(field["name"] + ":" + field["type"] for field in schema) + ")[\n"
    result += ",\n".join(source_rows) + "\n];\n"
    for name in (REGULAR, FILTERING, "vimEmailEventEmpty", "ASimEmailEvent", "imEmailEvent"):
        if name == "ASimEmailEvent":
            result += 'let _GetWatchlist = (name:string) { datatable(SearchKey:string, SourceSpecificParser:string)[] };\n'
        result += declaration(name)
    expected = ",\n".join(json.dumps(case["name"]) + ", dynamic(" + json.dumps(case["expected"]) + ")"
                          for case in fixtures["cases"])
    result += "let ExpectedMappings = datatable(CaseName:string, Expected:dynamic)[\n" + expected + "\n];\n"
    result += f'let Results = materialize(union ({REGULAR}(pack=true) | extend Variant="regular"), ({FILTERING}(pack=true) | extend Variant="filtering"));\n'
    result += """let MappingFailures = Results
| extend Actual = pack_all()
| lookup ExpectedMappings on $left.EventOriginalUid == $right.CaseName
| mv-expand Field = bag_keys(Expected)
| extend Field = tostring(Field)
| where tostring(Actual[Field]) != tostring(Expected[Field])
| project Test = strcat(Variant, ":", EventOriginalUid), Field, Expected=tostring(Expected[Field]), Actual=tostring(Actual[Field]);
"""
    tests = [
        count_test("regular-cardinality", REGULAR + "()", 14),
        count_test("filtering-cardinality", FILTERING + "()", 14),
        count_test("disabled-regular", REGULAR + "(disabled=true)", 0),
        count_test("disabled-filtering", FILTERING + "(disabled=true)", 0),
        count_test("time-inclusive", FILTERING + "(starttime=datetime(2026-10-15T12:00:00Z), endtime=datetime(2026-10-15T12:00:00Z))", 13),
        count_test("time-excludes", FILTERING + "(starttime=datetime(2026-10-16))", 0),
        count_test("sender-positive", FILTERING + '(emailfromaddress_has_any=dynamic(["example.com"]))', 14),
        count_test("sender-negative", FILTERING + '(emailfromaddress_has_any=dynamic(["missing.invalid"]))', 0),
        count_test("subject-positive", FILTERING + '(emailsubject_has_any=dynamic(["Synthetic"]))', 14),
        count_test("subject-negative", FILTERING + '(emailsubject_has_any=dynamic(["absentword"]))', 0),
        count_test("recipient-header", FILTERING + '(emailrecipient_has_any=dynamic(["bob@contoso.example"]))', 12),
        count_test("recipient-negative", FILTERING + '(emailrecipient_has_any=dynamic(["nobody@absent.invalid"]))', 0),
        count_test("ipv4-prefix", FILTERING + '(ipaddr_has_any_prefix=dynamic(["192.0.2."]))', 12),
        count_test("ipv6-prefix", FILTERING + '(ipaddr_has_any_prefix=dynamic(["2001:db8:"]))', 1),
        count_test("ipv6-prefix-case", FILTERING + '(ipaddr_has_any_prefix=dynamic(["2001:DB8:"]))', 1),
        count_test("literal-not-regex-prefix", FILTERING + '(ipaddr_has_any_prefix=dynamic(["192x0x2x"]))', 0),
        count_test("normalized-direction", FILTERING + '(emaildirection_in=dynamic(["Internal"]))', 1),
        count_test("normalized-location", FILTERING + '(emaildeliverylocation_in=dynamic(["Quarantine"]))', 1),
        count_test("result-failure", FILTERING + '(eventresult="Failure")', 2),
        count_test("result-na", FILTERING + '(eventresult="NA")', 1),
        count_test("packing-off", REGULAR + "() | where array_length(bag_keys(AdditionalFields)) != 0", 0),
        count_test("packing-on", REGULAR + "(pack=true) | where isempty(tostring(AdditionalFields.NetworkMessageId))", 0),
        count_test("missing-required-diagnostics", REGULAR + "() | where isnotempty(EventMessage)", 2),
        count_test("valid-required-fields", REGULAR + "() | where isnotnull(TimeGenerated) and isnotempty(Dst)", 12),
        count_test("regular-unified-workflow", "ASimEmailEvent()", 14),
        count_test("filtering-unified-workflow", 'imEmailEvent(eventresult="Failure", emaildirection_in=dynamic(["Inbound"]))', 2),
    ]
    result += "let ControlFailures = union\n" + ",\n".join(tests) + "\n| where Expected != Actual;\n"
    result += "union MappingFailures, ControlFailures | order by Test asc, Field asc\n"
    (HERE / "EmailEventsRegression.kql").write_text(result, encoding="utf-8")
    print(f"Generated {len(fixtures['cases'])} mapping cases for both variants and {len(tests)} control assertions.")


if __name__ == "__main__":
    build()
